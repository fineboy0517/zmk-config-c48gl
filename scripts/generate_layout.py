#!/usr/bin/env python3
"""Generate the 48-key transform and Studio geometry from public QMK/PCB evidence."""
import argparse
import json
from inspect_pcb import ROOT, footprints

def generated_layout():
    layout = json.loads((ROOT / 'research/qmk/info.json').read_text())['layouts']['LAYOUT']['layout']
    parts = footprints()
    positions = []
    for key in layout:
        row, col = key['matrix']
        switch = 1 + col * 4 + row % 4 + (24 if row >= 4 else 0)
        positions.append(parts[f'SW{switch}']['at'])
    min_x = min(p[0] for p in positions)
    min_y = min(p[1] for p in positions)
    text = ['// SPDX-License-Identifier: GPL-2.0-or-later',
            '// Generated by scripts/generate_layout.py; do not edit by hand.',
            '// Key order: QMK LAYOUT. Geometry: PCB SW1..SW48, 19.05 mm = 1u.',
            '#include <physical_layouts.dtsi>', '', '/ {',
            '    c48gl_transform: transform {',
            '        compatible = "zmk,matrix-transform";',
            '        rows = <10>;', '        columns = <10>;', '        map = <']
    coords = []
    for key in layout:
        row, col = key['matrix']
        coords.append((row, 4 + col) if row < 4 else (4 + col, row - 4))
    for start in range(0, 48, 12):
        text.append('            ' + ' '.join(f'RC({r},{c})' for r,c in coords[start:start+12]))
    text += ['        >;', '    };', '', '    c48gl_layout: physical_layout {',
             '        compatible = "zmk,physical-layout";',
             '        display-name = "C48GL 48 keys";',
             '        transform = <&c48gl_transform>;',
             '        kscan = <&kscan0>;', '        keys =']
    for i, (x,y,rot) in enumerate(positions):
        cx = round((x-min_x)/19.05*100) + 100
        cy = round((y-min_y)/19.05*100) + 100
        # KiCad rotation is counter-clockwise; ZMK uses clockwise.
        # MX footprints can be flipped 180 degrees for socket routing. A keycap
        # has the same axis in either orientation; keep Studio legends upright.
        rotation = round(((-rot + 90) % 180 - 90)*100)
        rotation_value = str(rotation) if rotation >= 0 else f'({rotation})'
        suffix = ';' if i == 47 else ','
        text.append(f'            <&key_physical_attrs 100 100 {cx-50} {cy-50} {rotation_value} {cx} {cy}>{suffix}')
    text += ['    };', '};', '']
    return '\n'.join(text)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'boards/shields/c48gl/c48gl-layout.dtsi'
    expected = generated_layout()
    if args.check:
        assert output.read_text() == expected, 'Layout is stale; run scripts/generate_layout.py'
        print('Physical layout and transform match QMK/PCB evidence (48 keys).')
    else:
        output.write_text(expected)
