#define JP_CARET EQUAL
#define JP_YEN INT_YEN
#define JP_BSLH INT_RO
#define JP_LPAR LS(N8)
#define JP_RPAR LS(N9)
#define JP_EQUAL LS(MINUS)
#define JP_PLUS LS(SEMI)
#define JP_UNDER LS(INT_RO)
#define JP_TILDE LS(EQUAL)
#define JP_PIPE LS(INT_YEN)
#define JP_LBRACE LS(RBKT)
#define JP_RBRACE LS(NON_US_HASH)
#define JP_DQUOTE LS(N2)
#define JP_SQUOTE LS(N7)
#define JP_AMPS LS(N6)
#define JP_STAR LS(SQT)
